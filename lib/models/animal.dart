class Animal {
  final String name;
  final String size;
  final int age;
  final String gender;
  final String type; // e.g., 'Cat', 'Dog', 'Other'
  final String preferences;

  Animal({
    required this.name,
    required this.size,
    required this.age,
    required this.gender,
    required this.type,
    required this.preferences,
  });
}
